import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import { makeAlbums } from '../src/lib/collections.ts';
import { configureCases } from '../src/lib/case-settings.ts';
const compiled = await build({ entryPoints: ['src/lib/game.ts'], bundle: true, format: 'esm', platform: 'node', write: false });
const { act, fresh } = await import('data:text/javascript;base64,' + Buffer.from(compiled.outputFiles[0].text).toString('base64'));
const raw = JSON.parse(readFileSync('src/lib/catalog.json', 'utf8'));
const boxes = configureCases(raw.cases, raw.items);
const albums = makeAlbums(raw.items, boxes);
assert.deepEqual(albums.map(a => a.items.length), [6, 6, 4, 6, 6, 4]);
assert.ok(albums.every(a => new Set(a.items.map(i => i.id)).size === a.items.length));
const owned = item => ({ uid: crypto.randomUUID(), id: item.id, value: Math.round(item.price * 100), at: 1 });
let state = fresh();
state.inventory = albums[0].items.map(owned);
state.opens = 100;
state = act(state, { type: 'appearance', background: 'nebula' }, 10).state;
assert.ok(state.progress.achievements.includes('album'));
assert.ok(state.progress.achievements.includes('hundred'));
assert.equal(state.progress.background, 'nebula');
const ids = state.inventory.map(i => i.uid);
state = act(state, { type: 'showcase', ids, title: 'Альбом' }, 20).state;
state = act(state, { type: 'lock', ids: [ids[0]], locked: true }, 30).state;
const snapshot = JSON.stringify(state);
assert.throws(() => act(state, { type: 'sell', ids }, 40));
assert.equal(JSON.stringify(state), snapshot);
state = act(state, { type: 'lock', ids: [ids[0]], locked: false }, 50).state;
state = act(state, { type: 'sell', ids }, 60).state;
assert.equal(state.inventory.length, 0);
assert.equal(state.progress.showcase.length, 0);
assert.equal(state.progress.acquired.length, 6);
assert.ok(state.progress.achievements.includes('album'));
assert.throws(() => act(state, { type: 'appearance', frame: 'gold' }, 70));
const knifeState = fresh(); knifeState.inventory = [owned(raw.items.find(i => i.type === 'knife'))];
assert.equal(act(knifeState, { type: 'appearance', frame: 'gold' }, 80).state.progress.frame, 'gold');
state = fresh(); state.balance = 10000000;
const box = boxes.find(b => b.id === 'einstein');
const item = raw.items.find(i => i.id === box.items[0].id);
const request = { type: 'open', caseId: box.id, count: 1, requestId: 'fixed-request' };
state = act(state, request, 100, () => 0).state;
assert.equal(state.progress.stats.caseSpent, 6900);
assert.equal(state.progress.stats.caseReturn, Math.round(item.price * 100));
const duplicate = act(state, request, 101, () => 0);
assert.equal(duplicate.result.duplicate, true);
assert.equal(duplicate.state.progress.stats.caseOpens, 1);
for (let i = 0; i < 210; i++) state = act(state, { type: 'open', caseId: box.id }, 200 + i, () => 0).state;
assert.equal(state.progress.stats.rounds.length, 200);
assert.equal(state.progress.stats.caseOpens, 211);
assert.equal(state.progress.stats.caseSpent, 211 * 6900);
assert.equal(state.progress.stats.bestDrop.id, item.id);
const before = JSON.stringify(state.progress);
state = act(state, { type: 'reset' }, 1000).state;
assert.equal(JSON.stringify(state.progress), before);
state = act(state, { type: 'lock', ids: [state.inventory[0].uid], locked: true }, 1100).state;
state = act(state, { type: 'showcase', ids: [state.inventory[0].uid], title: 'Сохранённая витрина' }, 1200).state;
state = act(state, { type: 'topup', amount: 50000, requestId: 'old-topup' }, 1300).state;
const saved = structuredClone(state);
assert.throws(() => act(state, { type: 'resetAll' }, 1400));
assert.deepEqual(state, saved);
const resetRequest = { type: 'resetAll', confirmReset: true, requestId: 'full-reset' };
state = act(state, resetRequest, 1500).state;
assert.equal(state.balance, 0); assert.equal(state.coins, 0); assert.equal(state.opens, 0);
assert.equal(state.pending, null); assert.deepEqual(state.inventory, []); assert.deepEqual(state.history, []);
const expected = act(fresh(), { type: 'showcase', ids: [] }, 1500).state;
assert.deepEqual(state.progress, expected.progress);
assert.equal(act(state, { type: 'topup', amount: 50000, requestId: 'old-topup' }, 1600).result.duplicate, true);
state = act(state, { type: 'topup', amount: 10000, requestId: 'new-topup' }, 1700).state;
const replay = act(state, resetRequest, 1800);
assert.equal(replay.result.duplicate, true);
assert.equal(replay.state.pending.amount, 10000);
assert.deepEqual(saved.inventory.length, 211, 'Reset never mutates input or another profile');
console.log('PASS: legacy inventory adoption, complete albums, reward gating, protected bulk operations, showcase cleanup, persistent collection progress, exact statistics, duplicate requests, bounded chart history.');
console.log('PASS: confirmed full reset, protected items, pending top-up cancellation, fresh progress, stale-request protection, safe duplicate reset.');
